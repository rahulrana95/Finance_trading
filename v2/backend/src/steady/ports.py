"""Interfaces the services depend on; adapters implement them."""

from threading import Lock
from typing import Protocol

from steady.domain import Close, Idea, Run, Screen


class PriceSourceError(Exception):
    """The price source could not give usable prices for a symbol."""


class PriceSource(Protocol):
    name: str
    official: bool

    def daily_closes(self, symbol: str) -> list[Close]:
        """Daily closes, oldest first. Raises PriceSourceError."""
        ...


class Store(Protocol):
    """Where runs and ideas are kept."""

    lock: Lock

    def add_run(self, run: Run) -> None: ...
    def save_run(self, run: Run) -> None: ...
    def runs(self) -> list[Run]: ...
    def run(self, run_id: str) -> Run | None: ...
    def save_idea(self, idea: Idea) -> None: ...
    def ideas(self) -> list[Idea]: ...
    def open_idea(self, symbol: str) -> Idea | None: ...
    def expire(self, idea: Idea) -> None: ...
    def save_screen(self, screen: Screen) -> None: ...
    def latest_screen(self) -> Screen | None: ...
    def close(self) -> None: ...
